    @staticmethod
    def _convert_types(obj):
        """转换不可 JSON 序列化的类型"""
        from decimal import Decimal
        if isinstance(obj, Decimal):
            return float(obj)
        elif isinstance(obj, datetime):
            return obj.strftime('%Y-%m-%d %H:%M:%S')
        elif isinstance(obj, date):
            return obj.strftime('%Y-%m-%d')
        elif isinstance(obj, time):
            return obj.strftime('%H:%M:%S')
        elif isinstance(obj, dict):
            return {k: SQLTranslatorProd._convert_types(v) for k, v in obj.items()}
        elif isinstance(obj, list):
            return [SQLTranslatorProd._convert_types(item) for item in obj]
        return obj

    def fetch_data_source(self, model_id, data_source_id=None):
        """
        从 Redis 查询数据源连接信息

        数据源同步规则（参考 SemanticModelRedisUtil.storeDataSources）：
        - key: semantic_model:data_source:{dataSourceId}
        - value: 数据源记录 JSON，包含 id/semantic_model_id/db_type/db_name/host/port/username/password/db_schema 等

        查询策略：
        1. 优先按 data_source_id 精确查找（O(1)）
        2. 否则按 model_id 扫描所有 data_source key，匹配 semantic_model_id 字段

        :param model_id: 语义模型 id（对应数据源记录中的 semantic_model_id 字段）
        :param data_source_id: 可选，直接指定数据源 id
        :return: 数据源配置字典 或 None
        """
        r = self.loader.redis

        # 策略1：按 data_source_id 精确查找
        if data_source_id:
            raw = r.get(f'{DATA_SOURCE_KEY_PREFIX}{data_source_id}')
            if raw:
                try:
                    ds = json.loads(raw)
                    if str(ds.get('semantic_model_id')) == str(model_id) if model_id else True:
                        return ds
                except (json.JSONDecodeError, TypeError):
                    pass

        # 策略2：按 model_id 扫描所有 data_source key
        if not model_id:
            return None
        for key in r.scan_iter(match=f'{DATA_SOURCE_KEY_PREFIX}*', count=1000):
            raw = r.get(key)
            if not raw:
                continue
            try:
                ds = json.loads(raw)
            except (json.JSONDecodeError, TypeError):
                continue
            # 跳过已删除记录
            if ds.get('is_deleted') in (1, True):
                continue
            if str(ds.get('semantic_model_id')) == str(model_id):
                return ds
        return None

    @staticmethod
    def _is_shared_region_hospital_denominator_subquery(sql: str) -> bool:
        """Allow only the governed scalar denominator used by hospital coverage.

        The public execute endpoint otherwise rejects every subquery.  This one
        exception is intentionally structural and narrow: it may only count
        distinct hospital-master IDs, may only join the published city/province
        lookup tables, and must constrain every joined lookup by equality.  It
        cannot read arbitrary columns, add UNION, reference dealer/order rows,
        or introduce another nested SELECT.
        """

        starts = list(re.finditer(r"\(\s*SELECT\b", sql, re.I))
        if len(starts) != 1:
            return False
        pattern = re.compile(
            r"\(\s*SELECT\s+COUNT\s*\(\s*DISTINCT\s+"
            r"denominator_hospital\.hospital_id\s*\)\s+"
            r"FROM\s+hospital\s+AS\s+denominator_hospital\s+"
            r"(?P<body>.*?)\)",
            re.I | re.S,
        )
        match = pattern.search(sql)
        if match is None or match.start() != starts[0].start():
            return False
        if re.search(r"\(\s*SELECT\b", sql[match.end():], re.I):
            return False

        body_parts = re.split(r"\bWHERE\b", match.group("body"), maxsplit=1, flags=re.I)
        if len(body_parts) != 2:
            return False
        join_text, predicate_text = body_parts
        allowed_joins = {
            "city": re.compile(
                r"JOIN\s+dim_city\s+AS\s+denominator_city\s+ON\s+"
                r"denominator_hospital\.city_id\s*=\s*"
                r"denominator_city\.city_id",
                re.I,
            ),
            "province": re.compile(
                r"JOIN\s+dim_province\s+AS\s+denominator_province\s+ON\s+"
                r"denominator_hospital\.province_id\s*=\s*"
                r"denominator_province\.province_id",
                re.I,
            ),
        }
        joined_regions: set[str] = set()
        residual_joins = join_text
        for region, join_pattern in allowed_joins.items():
            matches = list(join_pattern.finditer(residual_joins))
            if len(matches) > 1:
                return False
            if matches:
                joined_regions.add(region)
                residual_joins = join_pattern.sub(" ", residual_joins)
        if not joined_regions or residual_joins.strip():
            return False

        allowed_predicates = {
            "city": re.compile(
                r"denominator_city\.city_name\s*=\s*''", re.I
            ),
            "province": re.compile(
                r"denominator_province\.province_name\s*=\s*''", re.I
            ),
        }
        predicates = [
            item.strip()
            for item in re.split(r"\bAND\b", predicate_text, flags=re.I)
            if item.strip()
        ]
        filtered_regions: set[str] = set()
        for predicate in predicates:
            region = next(
                (
                    name for name, predicate_pattern in allowed_predicates.items()
                    if predicate_pattern.fullmatch(predicate)
                ),
                None,
            )
            if region is None or region in filtered_regions:
                return False
            filtered_regions.add(region)
        return filtered_regions == joined_regions

    @staticmethod
    def validate_read_only_sql(sql: str) -> str:
        """Validate the raw SQL boundary exposed by ``/api/execute``."""
        if not isinstance(sql, str) or not sql.strip():
            raise ValueError("SQL must be a non-empty string")
        if len(sql) > 200_000:
            raise ValueError("SQL exceeds the maximum accepted length")
        normalized = re.sub(r"/\*.*?\*/", " ", sql, flags=re.S)
        normalized = re.sub(r"--[^\r\n]*", " ", normalized)
        normalized = re.sub(r"'(?:''|\\.|[^'])*'", "''", normalized)
        normalized = re.sub(r'"(?:""|\\.|[^"])*"', '""', normalized)
        statements = [part.strip() for part in normalized.split(';') if part.strip()]
        if len(statements) != 1 or not re.match(r"^(SELECT|WITH)\b", statements[0], re.I):
            raise ValueError("only one read-only SELECT statement is allowed")
        prohibited = re.compile(
            r"\b(INSERT|UPDATE|DELETE|REPLACE|MERGE|CREATE|ALTER|DROP|TRUNCATE|"
            r"RENAME|GRANT|REVOKE|CALL|EXECUTE|PREPARE|HANDLER|LOAD|OUTFILE|"
            r"DUMPFILE|FOR\s+UPDATE|LOCK\s+IN\s+SHARE\s+MODE|GET_LOCK|"
            r"RELEASE_LOCK|SLEEP|BENCHMARK)\b|@@",
            re.I,
        )
        if prohibited.search(statements[0]):
            raise ValueError("SQL contains a prohibited operation")
        if (
            re.search(r'\(\s*SELECT\b', statements[0], re.I)
            and not SQLTranslatorProd._is_shared_region_hospital_denominator_subquery(
                statements[0]
            )
        ):
            raise ValueError("不允许执行子查询")
        return sql.strip()

    @staticmethod
    def _sql_involved_tables(sql: str) -> set[str]:
        """Extract simple physical FROM/JOIN tables, failing closed otherwise.

        SQL Translator emits ordinary ``FROM table [alias] JOIN table`` SQL.
        Watermark discovery intentionally supports only that shape. It does not
        reinterpret CTEs, derived tables or comma joins because missing one
        source table could make an ambiguous watermark look unique.
        """
        try:
            normalized = SQLTranslatorProd.validate_read_only_sql(sql)
        except ValueError:
            return set()
        scrubbed = re.sub(r"/\*.*?\*/", " ", normalized, flags=re.S)
        scrubbed = re.sub(r"--[^\r\n]*", " ", scrubbed)
        scrubbed = re.sub(r"'(?:''|\\.|[^'])*'", "''", scrubbed)
        scrubbed = re.sub(r'"(?:""|\\.|[^"])*"', '""', scrubbed)
        if re.match(r"^\s*WITH\b", scrubbed, re.I):
            return set()
        from_match = re.search(
            r"\bFROM\b(?P<body>.*?)(?:\bWHERE\b|\bGROUP\s+BY\b|"
            r"\bHAVING\b|\bORDER\s+BY\b|\bLIMIT\b|$)",
            scrubbed,
            re.I | re.S,
        )
        if not from_match or ',' in from_match.group('body'):
            return set()
        identifier = r"(?:`[A-Za-z_][A-Za-z0-9_]*`|[A-Za-z_][A-Za-z0-9_]*)"
        table_ref = re.compile(
            rf"\b(?:FROM|JOIN)\s+"
            rf"(?P<ref>{identifier}(?:\s*\.\s*{identifier})?)",
            re.I,
        )
        tables: set[str] = set()
        for match in table_ref.finditer(scrubbed):
            parts = [part.strip().strip('`') for part in match.group('ref').split('.')]
            table = parts[-1] if parts else ''
            if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', table):
                return set()
            tables.add(table)
        return tables

    @staticmethod
    def _is_time_dimension(dimension: Dict[str, Any]) -> bool:
        dim_type = str(dimension.get('dim_type') or '').strip().casefold()
        return dim_type in {
            'time', 'date', 'datetime', 'timestamp',
            '时间', '日期', '时间维度', '日期维度',
        }

    @staticmethod
    def _dimension_physical_fields(dimension: Dict[str, Any]) -> set[str]:
        """Return only identifier-safe fields explicitly mapped by metadata."""
        raw_fields = {
            str(item.get('field_path') or '').strip()
            for item in dimension.get('attribute_mappings', []) or []
            if isinstance(item, dict)
        }
        raw_fields.discard('')
        identifier = re.compile(
            r'[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*'
        )
        if not raw_fields or any(not identifier.fullmatch(field) for field in raw_fields):
            return set()
        return raw_fields

    def _resolve_source_watermark_field(
        self, sql: str, model_id: Optional[str]
    ) -> Optional[str]:
        """Resolve the one trustworthy business-time field for this query."""
        if model_id is None:
            return None
        try:
            normalized_model_id = str(_positive_int(model_id))
        except ValueError:
            return None
        involved_tables = self._sql_involved_tables(sql)
        if not involved_tables:
            return None
        try:
            dimensions = self.loader.iter_scoped_dimensions(normalized_model_id)
        except (redis.RedisError, ValueError, TypeError):
            return None
        candidates: set[str] = set()
        for dimension in dimensions:
            if not isinstance(dimension, dict) or not self._is_time_dimension(dimension):
                continue
            fields = self._dimension_physical_fields(dimension)
            # Composite year/month mappings are not one real timestamp field.
            if len(fields) != 1:
                continue
            field = next(iter(fields))
            if field.split('.', 1)[0] in involved_tables:
                candidates.add(field)
        return next(iter(candidates)) if len(candidates) == 1 else None

    @staticmethod
    def _safe_watermark_identifier(field: Optional[str]) -> Optional[tuple[str, str]]:
        if not isinstance(field, str) or not re.fullmatch(
            r'[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*', field
        ):
            return None
        table, column = field.split('.', 1)
        return table, column

    @staticmethod
    def _serialize_source_watermark(value: Any) -> Optional[str]:
        if isinstance(value, datetime):
            return value.isoformat(timespec='microseconds')
        if isinstance(value, date):
            return value.isoformat()
        return None

    @staticmethod
    def execute_sql_on_data_source(
        sql: str,
        ds_config: Dict,
        source_watermark_field: Optional[str] = None,
    ) -> Dict:
        """
        在指定数据源上执行 SQL

        :param sql: SQL 语句
        :param ds_config: 数据源配置（host/port/user/password/database）
        :return: 执行结果字典
        """
        try:
            sql = SQLTranslatorProd.validate_read_only_sql(sql)
        except ValueError:
            return {
                'success': False,
                'error': 'SQL was rejected by the read-only safety policy',
                'error_code': 'SQL_SAFETY_REJECTED',
                'retryable': False,
            }

        db_type = (ds_config.get('db_type') or '').lower()
        if db_type and 'mysql' not in db_type and 'maria' not in db_type:
            return {
                'success': False,
                'error': f"暂不支持的数据源类型: {db_type}，当前仅支持 MySQL"
            }

        connection = None
        try:
            connection = pymysql.connect(
                host=ds_config.get('host', '').split(':')[0],
                port=int(ds_config.get('port') or 3306),
                user=ds_config.get('username', ''),
                password=ds_config.get('password', ''),
                database=ds_config.get('db_name', ''),
                charset='utf8mb4',
                cursorclass=DictCursor,
            )
            with connection.cursor() as cursor:
                # Establish an actual read-only consistent snapshot before the
                # business query. If the source does not support this contract,
                # the query may still succeed but no PASS evidence is emitted.
                snapshot_time = None
                snapshot_verified = False
                try:
                    cursor.execute("SET TRANSACTION READ ONLY")
                    cursor.execute("START TRANSACTION WITH CONSISTENT SNAPSHOT")
                    cursor.execute("SELECT UTC_TIMESTAMP(6) AS data_as_of")
                    snapshot_row = cursor.fetchone() or {}
                    snapshot_time = snapshot_row.get('data_as_of')
                    snapshot_verified = isinstance(snapshot_time, datetime)
                except Exception:
                    connection.rollback()
                cursor.execute(sql)
                result_data = cursor.fetchall()
                columns = [desc[0] for desc in cursor.description] if cursor.description else []
                source_watermark = None
                safe_watermark_field = SQLTranslatorProd._safe_watermark_identifier(
                    source_watermark_field
                )
                if snapshot_verified and safe_watermark_field:
                    table, column = safe_watermark_field
                    try:
                        cursor.execute(
                            f"SELECT MAX(`{table}`.`{column}`) AS source_data_as_of "
                            f"FROM `{table}`"
                        )
                        watermark_row = cursor.fetchone() or {}
                        source_watermark = SQLTranslatorProd._serialize_source_watermark(
                            watermark_row.get('source_data_as_of')
                        )
                    except Exception:
                        # The business result remains usable. Optional evidence
                        # that cannot be verified is omitted instead of guessed.
                        source_watermark = None
                result_data = SQLTranslatorProd._convert_types(result_data)
                result = {
                    'success': True,
                    'data': result_data,
                    'columns': columns,
                    'row_count': len(result_data),
                    'error': None,
                }
                integrity_verified = (
                    snapshot_verified
                    and len(columns) == len(set(columns))
                    and all(isinstance(column, str) and column for column in columns)
                    and all(
                        isinstance(row, dict) and set(row) == set(columns)
                        for row in result_data
                    )
                )
                if integrity_verified:
                    data_as_of = snapshot_time.replace(tzinfo=timezone.utc)
                    source_identity = {
                        'id': str(ds_config.get('id') or ''),
                        'semantic_model_id': str(ds_config.get('semantic_model_id') or ''),
                        'db_name': str(ds_config.get('db_name') or ''),
                    }
                    digest = hashlib.sha256(json.dumps(
                        {
                            'source': source_identity,
                            'sql': sql,
                            'columns': columns,
                            'rows': result_data,
                            'data_as_of': data_as_of.isoformat(),
                            'source_data_as_of': source_watermark,
                            'source_watermark_field': (
                                source_watermark_field if source_watermark else None
                            ),
                        },
                        ensure_ascii=False,
                        sort_keys=True,
                        separators=(',', ':'),
                        default=str,
                    ).encode('utf-8')).hexdigest()
                    result.update({
                        'snapshot_id': f'mysql-consistent:{digest}',
                        'data_as_of': data_as_of.isoformat().replace('+00:00', 'Z'),
                        'quality_status': 'PASS',
                        'quality_checks': {
                            'consistent_snapshot': True,
                            'read_only_transaction': True,
                            'column_contract_valid': True,
                            'row_contract_valid': True,
                            'row_count_reconciled': True,
                        },
                    })
                    if source_watermark:
                        result.update({
                            'source_data_as_of': source_watermark,
                            'source_watermark_field': source_watermark_field,
                        })
                return result
        except Exception as e:
            return {'success': False, 'error': f"数据库执行错误: {str(e)}"}
        finally:
            if connection:
                connection.close()

