def ast_to_sql(ast_json: str, redis_config: Optional[Dict] = None) -> Dict:
    """
    便捷接口函数：传入 AST 结构化 JSON，返回查询结果

    :param ast_json: AST 结构化数据的 JSON 字符串
        AST 顶层应包含 model_id（语义模型id）或 data_source_id 字段，
        用于关联数据源并执行查询。
    :param redis_config: 可选的 Redis 配置，默认使用内置配置
    :return: 查询结果字典，包含以下字段:
        - sql: 生成的 SQL 语句
        - success: 是否执行成功
        - data: 查询结果数据
        - columns: 列名列表
        - row_count: 行数
        - error: 错误信息
        - data_source: 数据源信息

    使用示例:
        >>> ast_json = '''{
        ...     "version": "2.0",
        ...     "intent": "query",
        ...     "model_id": 1,
        ...     "subject": {"entity": "ent_order"},
        ...     "metrics": [{"name": "order_count", "alias": "订单数"}],
        ...     "dimensions": [{"name": "dim_channel_type"}],
        ...     "filters": [],
        ...     "time_context": null,
        ...     "sort": null,
        ...     "limit": null,
        ...     "ambiguity": []
        ... }'''
        >>> result = ast_to_sql(ast_json)
    """
    translator = SQLTranslatorProd(redis_config)
    return translator.execute_query(ast_json)


