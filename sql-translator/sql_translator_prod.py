class SemanticCatalog:
    """Read-only metric definition and lineage catalog backed by semantic MySQL.

    This catalog is deliberately separate from Redis translation caches. Redis is
    optimized for ASL translation; MySQL remains the authoritative source for
    definitions, aliases and lineage returned to callers.
    """

    def __init__(self, db_config: Optional[Dict] = None):
        self.db_config = db_config or {
            'host': os.getenv('MYSQL_HOST', '127.0.0.1'),
            'port': int(os.getenv('MYSQL_PORT', '3306')),
            'user': os.getenv('MYSQL_USER', ''),
            'password': os.getenv('MYSQL_PASSWORD', ''),
            'database': os.getenv('MYSQL_DATABASE', ''),
            'charset': 'utf8mb4',
        }
        self._attribute_metadata_cache: Dict[tuple[int, str], List[Dict]] = {}
        self._entity_graph_cache: Dict[int, tuple[float, Dict[str, Dict]]] = {}
        self._dimension_metadata_cache: Dict[tuple[int, str], tuple[float, Optional[Dict]]] = {}

    def _query(self, sql: str, params=()) -> List[Dict]:
        connection = pymysql.connect(
            **self.db_config,
            cursorclass=DictCursor,
            connect_timeout=10,
            read_timeout=20,
        )
        try:
            with connection.cursor() as cursor:
                cursor.execute(sql, params)
                return list(cursor.fetchall())
        finally:
            connection.close()

    @staticmethod
    def _list_value(value: Any) -> List[str]:
        if value is None or value == '':
            return []
        if isinstance(value, list):
            return [str(item).strip() for item in value if str(item).strip()]
        text = str(value).strip()
        try:
            parsed = json.loads(text)
            if isinstance(parsed, list):
                return [str(item).strip() for item in parsed if str(item).strip()]
        except (json.JSONDecodeError, TypeError):
            pass
        # Support historical values such as '"销售额", "GMV"'.
        return [part.strip().strip('"\'') for part in text.split(',') if part.strip().strip('"\'')]

    @staticmethod
    def _metric_scope(metric_id: str) -> tuple[int, str]:
        if not isinstance(metric_id, str) or ':' not in metric_id:
            raise ValueError('metric_id必须使用semantic_model_id:metric_code格式')
        model, code = metric_id.split(':', 1)
        model_id = _positive_int(model)
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', code or ''):
            raise ValueError('metric_code格式不合法')
        return model_id, code

    def attribute_metadata(self, model_id: Any, fields: List[str]) -> Dict[str, List[Dict]]:
        """Load authoritative semantic roles for exact physical attributes."""
        model_id = _positive_int(model_id)
        normalized = list(dict.fromkeys(
            str(field).strip()
            for field in fields
            if re.fullmatch(r'[A-Za-z_]\w*\.[A-Za-z_]\w*', str(field).strip())
        ))
        if not normalized:
            return {}
        cache = getattr(self, '_attribute_metadata_cache', None)
        if cache is None:
            cache = self._attribute_metadata_cache = {}
        missing = [field for field in normalized if (model_id, field) not in cache]
        if missing:
            pairs = [field.split('.', 1) for field in missing]
            predicates = ' OR '.join(
                '(mapping_table=%s AND mapping_column=%s)' for _ in pairs
            )
            params: List[Any] = [model_id]
            for table, column in pairs:
                params.extend((table, column))
            rows = self._query(
                "SELECT mapping_table, mapping_column, is_main_attribute, "
                "is_primary_key, is_unique, is_required "
                "FROM semantic_model_attribute_config "
                "WHERE semantic_model_id=%s AND is_deleted=0 AND (" + predicates + ")",
                tuple(params),
            )
            grouped: Dict[str, List[Dict]] = {field: [] for field in missing}
            for row in rows:
                field = f"{row.get('mapping_table')}.{row.get('mapping_column')}"
                if field in grouped:
                    grouped[field].append(row)
            for field, metadata in grouped.items():
                cache[(model_id, field)] = metadata
        return {
            field: list(cache.get((model_id, field), []))
            for field in normalized
        }

    def registered_temporal_fields(self, model_id: Any) -> List[str]:
        """Return current physical DATE/TIME fields registered for one model.

        These fields may serve as a detail-query time projection even when the
        entity designer did not duplicate the timestamp as a public attribute.
        Keeping this lookup temporal-only avoids making arbitrary source
        columns queryable through the semantic ASL contract.
        """
        model_id = _positive_int(model_id)
        rows = self._query(
            "SELECT t.name AS table_name, f.name AS field_name "
            "FROM semantic_model_field f "
            "JOIN semantic_model_table t ON t.id=f.table_id "
            "AND t.semantic_model_id=f.semantic_model_id "
            "WHERE f.semantic_model_id=%s AND f.is_deleted=0 "
            "AND t.is_deleted=0 AND UPPER(f.type) IN "
            "('DATE','DATETIME','TIMESTAMP')",
            (model_id,),
        )
        return list(dict.fromkeys(
            f"{row.get('table_name')}.{row.get('field_name')}"
            for row in rows
            if re.fullmatch(
                r'[A-Za-z_]\w*\.[A-Za-z_]\w*',
                f"{row.get('table_name')}.{row.get('field_name')}",
            )
        ))

    def clear_cache(self, model_id: Any = None) -> int:
        """Invalidate cached attribute roles after semantic metadata refresh."""
        cache = getattr(self, '_attribute_metadata_cache', None) or {}
        normalized_model_id = _positive_int(model_id) if model_id is not None else None
        keys = [
            key for key in cache
            if normalized_model_id is None or key[0] == normalized_model_id
        ]
        for key in keys:
            cache.pop(key, None)
        graph_cache = getattr(self, '_entity_graph_cache', None)
        graph_removed = 0
        if graph_cache is not None:
            graph_keys = [
                key for key in graph_cache
                if normalized_model_id is None or key == normalized_model_id
            ]
            for key in graph_keys:
                graph_cache.pop(key, None)
            graph_removed = len(graph_keys)
        dimension_cache = getattr(self, '_dimension_metadata_cache', None)
        dimension_removed = 0
        if dimension_cache is not None:
            dimension_keys = [
                key for key in dimension_cache
                if normalized_model_id is None or key[0] == normalized_model_id
            ]
            for key in dimension_keys:
                dimension_cache.pop(key, None)
            dimension_removed = len(dimension_keys)
        return len(keys) + graph_removed + dimension_removed

    def dimension_metadata(self, model_id: Any, dim_code: str) -> Optional[Dict]:
        """Return the current published dimension from authoritative MySQL.

        Redis is a low-latency delivery cache and can briefly lag a semantic
        publish. Translation must not keep using an obsolete physical mapping
        during that window, so the current MySQL row overlays the Redis payload.
        """
        model_id = _positive_int(model_id)
        dim_code = str(dim_code or '').strip()
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', dim_code):
            return None
        if not hasattr(self, '_dimension_metadata_cache'):
            self._dimension_metadata_cache = {}
        key = (model_id, dim_code)
        now = time_module.monotonic()
        cached = self._dimension_metadata_cache.get(key)
        if cached is not None and now - cached[0] < 5.0:
            return dict(cached[1]) if cached[1] is not None else None
        rows = self._query(
            "SELECT * FROM semantic_model_dimension "
            "WHERE semantic_model_id=%s AND dim_code=%s AND is_deleted=0 "
            "ORDER BY update_time DESC,id DESC LIMIT 1",
            (model_id, dim_code),
        )
        current = dict(rows[0]) if rows else None
        if current is not None:
            for field in (
                'synonyms', 'special_rules', 'enum_list', 'level_list',
                'date_list', 'entity_attribute', 'indicator',
            ):
                raw = current.get(field)
                if isinstance(raw, str):
                    try:
                        current[field] = json.loads(raw) if raw.strip() else []
                    except (json.JSONDecodeError, TypeError):
                        current[field] = []
        self._dimension_metadata_cache[key] = (now, current)
        return dict(current) if current is not None else None

    def entity_relationship_metadata(self, model_id: Any) -> Dict[str, Dict]:
        """Return the authoritative published entity relation graph.

        Redis remains the low-latency payload, while this short-lived MySQL
        view repairs rolling publisher payloads that omit entity IDs or one of
        a bridge table's endpoint mappings. No physical relationship is inferred
        outside the published semantic tables.
        """
        model_id = _positive_int(model_id)
        now = time_module.monotonic()
        cached = getattr(self, '_entity_graph_cache', {}).get(model_id)
        if cached is not None and now - cached[0] < 5.0:
            return cached[1]
        entities = self._query(
            "SELECT id,code,main_table_name FROM semantic_model_entity_type "
            "WHERE semantic_model_id=%s AND status=1 AND is_deleted=0",
            (model_id,),
        )
        by_id = {
            str(row.get('id')): str(row.get('code'))
            for row in entities
            if row.get('id') and row.get('code')
        }
        graph: Dict[str, Dict] = {
            str(row['code']): {
                'entity_id': str(row.get('id') or ''),
                'base_table': str(row.get('main_table_name') or row['code']),
                'relations': [],
                'sub_table_mappings': [],
            }
            for row in entities if row.get('code')
        }
        relations = self._query(
            "SELECT code,type,source_entity_type_id,target_entity_type_id,"
            "source_table_column_name,target_table_column_name "
            "FROM semantic_model_relation_config WHERE semantic_model_id=%s "
            "AND status=1 AND is_deleted=0",
            (model_id,),
        )
        for row in relations:
            source_code = by_id.get(str(row.get('source_entity_type_id') or ''))
            target_code = by_id.get(str(row.get('target_entity_type_id') or ''))
            source_column = str(row.get('source_table_column_name') or '').replace('-', '.')
            target_column = str(row.get('target_table_column_name') or '').replace('-', '.')
            if not source_code or not target_code or not source_column or not target_column:
                continue
            graph[source_code]['relations'].append({
                'relation_code': str(row.get('code') or ''),
                'target_entity': target_code,
                'join_key': f"{source_column} = {target_column}",
                'relation_type': str(row.get('type') or ''),
            })
        mappings = self._query(
            "SELECT entity_type_id,sub_table_name,main_join_column,sub_join_column "
            "FROM semantic_model_entity_sub_table_mapping "
            "WHERE semantic_model_id=%s AND is_deleted=0",
            (model_id,),
        )
        for row in mappings:
            code = by_id.get(str(row.get('entity_type_id') or ''))
            if not code or not row.get('sub_table_name'):
                continue
            graph[code]['sub_table_mappings'].append({
                'sub_table_name': str(row.get('sub_table_name')),
                'main_join_column': str(row.get('main_join_column') or ''),
                'sub_join_column': str(row.get('sub_join_column') or ''),
            })
        self._entity_graph_cache[model_id] = (now, graph)
        return graph

    def infer_unique_bridge_endpoint(
        self, model_id: Any, bridge_table: str, entity_code: str
    ) -> Optional[Dict[str, str]]:
        """Resolve an omitted bridge endpoint only from registered fields.

        Historical publisher payloads can contain the relation's source half
        while omitting the target sub-table mapping. A mapping is recoverable
        only when the registered bridge fields and target-entity attributes
        share exactly one column name; otherwise callers must repair metadata.
        """
        model_id = _positive_int(model_id)
        if not re.fullmatch(r'[A-Za-z_]\w*', bridge_table or ''):
            return None
        if not re.fullmatch(r'[A-Za-z_]\w*', entity_code or ''):
            return None
        bridge_rows = self._query(
            "SELECT DISTINCT f.name FROM semantic_model_table t "
            "JOIN semantic_model_field f ON f.semantic_model_id=t.semantic_model_id "
            "AND f.table_id=t.id AND f.is_deleted=0 "
            "WHERE t.semantic_model_id=%s AND t.name=%s AND t.is_deleted=0",
            (model_id, bridge_table),
        )
        entity_rows = self._query(
            "SELECT DISTINCT a.mapping_column FROM semantic_model_attribute_config a "
            "JOIN semantic_model_entity_type e ON e.semantic_model_id=a.semantic_model_id "
            "AND e.id=a.entity_type_id AND e.is_deleted=0 "
            "WHERE a.semantic_model_id=%s AND e.code=%s AND a.is_deleted=0 "
            "AND a.mapping_table=e.main_table_name",
            (model_id, entity_code),
        )
        bridge_fields = {
            str(row.get('name')) for row in bridge_rows if row.get('name')
        }
        entity_fields = {
            str(row.get('mapping_column'))
            for row in entity_rows if row.get('mapping_column')
        }
        candidates = sorted(bridge_fields & entity_fields)
        if len(candidates) != 1:
            return None
        return {
            'sub_table_name': bridge_table,
            'main_join_column': candidates[0],
            'sub_join_column': candidates[0],
        }

    def resolve_metrics(self, model_id: Any, names: List[str]) -> Dict:
        model_id = _positive_int(model_id)
        if not isinstance(names, list) or not names:
            raise ValueError('metric_names必须是非空数组')
        rows = self._query(
            "SELECT indicator_code, indicator_name, synonyms, unit, business_domain_id "
            "FROM semantic_model_indicator WHERE semantic_model_id=%s AND is_deleted=0",
            (model_id,),
        )
        exact: Dict[str, List[Dict]] = {}
        for row in rows:
            terms = [row.get('indicator_code'), row.get('indicator_name')]
            terms.extend(self._list_value(row.get('synonyms')))
            for term in terms:
                if term is not None and str(term).strip():
                    exact.setdefault(str(term).strip().casefold(), []).append(row)
        resolved, unresolved, ambiguities = [], [], []
        for raw_name in names:
            name = str(raw_name).strip()
            candidates = exact.get(name.casefold(), [])
            if not candidates:
                unresolved.append(name)
            elif len(candidates) > 1:
                ambiguities.append({
                    'input': name,
                    'candidates': [f"{model_id}:{row['indicator_code']}" for row in candidates],
                })
            else:
                row = candidates[0]
                resolved.append({
                    'input': name,
                    'metric_id': f"{model_id}:{row['indicator_code']}",
                    'version': 'current',
                    'canonical_name': row.get('indicator_name') or row['indicator_code'],
                    'unit': row.get('unit'),
                })
        status = 'RESOLVED'
        if ambiguities:
            status = 'AMBIGUOUS'
        elif unresolved:
            status = 'NOT_FOUND'
        return {
            'status': status,
            'semantic_model_id': model_id,
            'metrics': resolved,
            'unresolved': unresolved,
            'ambiguities': ambiguities,
        }

    def _metric_row(self, model_id: int, code: str) -> Dict:
        rows = self._query(
            "SELECT * FROM semantic_model_indicator "
            "WHERE semantic_model_id=%s AND indicator_code=%s AND is_deleted=0 LIMIT 1",
            (model_id, code),
        )
        if not rows:
            raise ValueError(f'不存在指标: {code}')
        return rows[0]

    def definition(self, metric_id: str, version: str, model_id: Any = None) -> Dict:
        scoped_model_id, code = self._metric_scope(metric_id)
        if model_id is not None and _positive_int(model_id) != scoped_model_id:
            raise ValueError('metric_id与semantic_model_id作用域不一致')
        row = self._metric_row(scoped_model_id, code)
        bindings = self._query(
            "SELECT b.entity_code, COALESCE(e.code, b.entity_code) AS resolved_entity_code, b.indicator_logic, "
            "e.name AS entity_name, e.main_table_name, e.data_source_id "
            "FROM semantic_model_entity_bind_indicator b "
            "LEFT JOIN semantic_model_entity_type e ON e.semantic_model_id=b.semantic_model_id "
            "AND e.code=b.entity_code AND e.is_deleted=0 "
            "WHERE b.semantic_model_id=%s AND b.indicator_code=%s AND b.is_deleted=0",
            (scoped_model_id, code),
        )
        formula = row.get('calculation_formula') or row.get('indicator_logic') or ''
        return {
            'metric_id': metric_id,
            'version': version or 'current',
            'semantic_model_id': scoped_model_id,
            'business_domain_id': row.get('business_domain_id'),
            'metric_code': code,
            'metric_name': row.get('indicator_name') or code,
            'metric_level': row.get('indicator_level'),
            'unit': row.get('unit'),
            'format_rule': row.get('format_rule'),
            'description': row.get('business_desc'),
            'synonyms': self._list_value(row.get('synonyms')),
            'applicable_scenarios': self._list_value(row.get('applicable_scenarios')),
            'calculation_formula': formula,
            'global_filters': self._list_value(row.get('global_filters')),
            'depend_metrics': self._list_value(row.get('dependence_atomic_indicator')),
            'bound_entities': bindings,
        }

    @staticmethod
    def _formula_fields(formula: str) -> List[str]:
        return sorted(set('.'.join(pair) for pair in re.findall(
            r'\b([A-Za-z_][A-Za-z0-9_]*)\.([A-Za-z_][A-Za-z0-9_]*)\b', formula or ''
        )))

    def lineage(self, metric_id: str, version: str) -> Dict:
        definition = self.definition(metric_id, version)
        model_id = definition['semantic_model_id']
        fields = self._formula_fields(definition.get('calculation_formula') or '')
        tables = sorted({field.split('.', 1)[0] for field in fields})
        table_rows = self._query(
            "SELECT id, name, data_source_id, description, comment FROM semantic_model_table "
            "WHERE semantic_model_id=%s",
            (model_id,),
        )
        field_rows = self._query(
            "SELECT f.id, f.name, f.type, f.null_flag, f.description, f.comment, t.name AS table_name "
            "FROM semantic_model_field f LEFT JOIN semantic_model_table t ON t.id=f.table_id "
            "WHERE f.semantic_model_id=%s",
            (model_id,),
        )
        table_map = {row.get('name'): row for row in table_rows}
        field_map = {f"{row.get('table_name')}.{row.get('name')}": row for row in field_rows}
        nodes = [{
            'id': metric_id, 'type': 'METRIC', 'name': definition['metric_name'],
        }]
        edges = []
        for entity in definition.get('bound_entities', []):
            entity_id = f"entity:{entity.get('entity_code')}"
            nodes.append({'id': entity_id, 'type': 'ENTITY', 'name': entity.get('entity_name')})
            edges.append({'from': entity_id, 'to': metric_id, 'type': 'DEFINES'})
        for table in tables:
            row = table_map.get(table)
            table_id = f'table:{table}'
            nodes.append({'id': table_id, 'type': 'TABLE', 'name': table, 'registered': row is not None})
            edges.append({'from': table_id, 'to': metric_id, 'type': 'FEEDS'})
        for field in fields:
            row = field_map.get(field)
            field_id = f'field:{field}'
            nodes.append({
                'id': field_id, 'type': 'FIELD', 'name': field,
                'registered': row is not None,
                'data_type': row.get('type') if row else None,
            })
            edges.append({'from': field_id, 'to': f"table:{field.split('.', 1)[0]}", 'type': 'BELONGS_TO'})

        dependency_metrics = []
        for dep_code in definition.get('depend_metrics', []):
            dep_id = f'{model_id}:{dep_code}'
            dep_row = self._metric_row(model_id, dep_code)
            dep = {
                'metric_id': dep_id,
                'version': version or 'current',
                'metric_code': dep_code,
                'metric_name': dep_row.get('indicator_name') or dep_code,
                'calculation_formula': dep_row.get('calculation_formula') or dep_row.get('indicator_logic') or '',
            }
            dependency_metrics.append(dep)
            edges.append({'from': dep_id, 'to': metric_id, 'type': 'DEPENDS_ON'})
            for dep_field in self._formula_fields(dep.get('calculation_formula') or ''):
                if dep_field not in fields:
                    fields.append(dep_field)
        warnings = []
        for field in fields:
            if field not in field_map:
                warnings.append(f'字段未在语义层注册: {field}')
        business_lineage = (
            [f"业务域:{definition['business_domain_id']}"]
            if definition.get('business_domain_id') is not None else []
        ) + [
            str(entity.get('entity_name') or entity.get('entity_code')).strip()
            for entity in definition.get('bound_entities', [])
            if entity.get('entity_name') or entity.get('entity_code')
        ]
        if definition.get('metric_name'):
            business_lineage.append(str(definition['metric_name']))
        formula = definition.get('calculation_formula') or ''
        physical_sources = []
        column_lineage = []
        for field in sorted(fields):
            table, column = field.split('.', 1)
            registered = field in field_map
            physical_sources.append({
                'table': table,
                'field': column,
                'transformation': formula,
                'registered': registered,
                'data_type': field_map[field].get('type') if registered else None,
                'lineage_source': 'SEMANTIC_FORMULA',
            })
            column_lineage.append({
                'from_columns': [field],
                'to_column': metric_id,
                'function': formula,
                'source': 'SEMANTIC_FORMULA',
            })
        upstream_edges = [
            {
                'from_entity': f'table:{table}',
                'to_entity': metric_id,
                'source': 'SEMANTIC_FORMULA',
                'columns_lineage': [
                    item for item in column_lineage
                    if item['from_columns'][0].split('.', 1)[0] == table
                ],
            }
            for table in sorted({field.split('.', 1)[0] for field in fields})
        ]
        return {
            'lineage_version': '2.0',
            'metric_id': metric_id,
            'version': version or 'current',
            'entity': {'id': metric_id, 'type': 'METRIC', 'name': definition['metric_name']},
            'business_lineage': business_lineage,
            'physical_sources': physical_sources,
            'source_tables': sorted({field.split('.', 1)[0] for field in fields}),
            'source_fields': sorted(fields),
            'dependency_metrics': dependency_metrics,
            'nodes': nodes,
            'edges': edges,
            'upstream_edges': upstream_edges,
            'downstream_edges': [],
            'column_lineage': column_lineage,
            'metadata_warnings': warnings,
        }


class RedisDSLLoader:
    """
    从 Redis 加载语义模型 DSL 数据，并将其适配为翻译器内部格式

    内部格式与原 yml 文件结构对齐，便于复用翻译器核心逻辑：
    - entity: {entity_code, entity_name, physical_table_join.base_table, relations[{target_entity, join_key}]}
    - metric: {metric_code, metric_name, metric_level, calculation_rule{calc_formula, global_filters, depend_metrics}, source_dependency.bind_entity}
    - dimension: {dim_code, dim_name, dim_type, enum_list, field_mapping{fact_table_field, dim_table_field}, bind_entities[{entity_code}]}
    """

    def __init__(self, redis_config: Optional[Dict] = None):
        self.redis_config = redis_config or REDIS_CONFIG
        self._redis = None
        # 缓存：避免重复读取 Redis，key 格式为 (model_id, code)
        self._entity_cache: Dict[tuple, Dict] = {}
        self._metric_cache: Dict[tuple, Dict] = {}
        self._dimension_cache: Dict[tuple, Dict] = {}
        # Publishing semantic metadata updates Redis, but the translator is a
        # long-running process. Keep the adapted-object cache short lived so a
        # missed publisher callback cannot leave an old formula resident until
        # the next service restart. The explicit /api/cache/refresh endpoint is
        # still the immediate/primary invalidation mechanism.
        self._cache_loaded_at: Dict[tuple, float] = {}
        try:
            self._cache_ttl_seconds = max(
                0.0, float(os.getenv("SEMANTIC_DSL_CACHE_TTL_SECONDS", "5"))
            )
        except (TypeError, ValueError):
            self._cache_ttl_seconds = 5.0
        # 表名 -> [entity_code] 映射（初始化时构建，同表多实体时保留全部候选）
        self._table_to_entity: Dict[str, list] = {}
        # 实体UUID(id) -> entity_code 映射，用于 relation_config 中的 target/source_entity_type_id 反查
        self._entity_id_to_code: Dict[str, str] = {}
        self._index_built_model_id = None  # 记录已构建索引的 model_id
        self._index_built_global = False  # 是否已构建全局索引（老格式）

    @property
    def redis(self):
        """惰性连接 Redis"""
        if self._redis is None:
            self._redis = redis.Redis(**self.redis_config)
        return self._redis

    def clear_cache(self, model_id: Optional[str] = None) -> Dict[str, int]:
        """Invalidate adapted DSL objects after semantic metadata changes."""
        caches = (self._entity_cache, self._metric_cache, self._dimension_cache)
        removed = {'entity': 0, 'metric': 0, 'dimension': 0}
        names = ('entity', 'metric', 'dimension')
        for name, cache in zip(names, caches):
            keys = list(cache)
            if model_id is not None:
                keys = [key for key in keys if str(key[0]) == str(model_id)]
            for key in keys:
                cache.pop(key, None)
                getattr(self, '_cache_loaded_at', {}).pop((name, *key), None)
            removed[name] = len(keys)
        # Entity lookup indexes are derived from Redis and must be rebuilt too.
        self._table_to_entity.clear()
        self._entity_id_to_code.clear()
        self._index_built_model_id = None
        self._index_built_global = False
        return removed

    def _cached(self, kind: str, cache: Dict[tuple, Dict], key: tuple) -> Optional[Dict]:
        value = cache.get(key)
        if value is None:
            return None
        loaded_at = getattr(self, '_cache_loaded_at', {}).get((kind, *key), 0.0)
        ttl = getattr(self, '_cache_ttl_seconds', 5.0)
        if ttl > 0 and time_module.monotonic() - loaded_at < ttl:
            return value
        cache.pop(key, None)
        getattr(self, '_cache_loaded_at', {}).pop((kind, *key), None)
        return None

    def _store_cached(self, kind: str, cache: Dict[tuple, Dict], key: tuple, value: Dict) -> Dict:
        cache[key] = value
        if not hasattr(self, '_cache_loaded_at'):
            self._cache_loaded_at = {}
        self._cache_loaded_at[(kind, *key)] = time_module.monotonic()
        return value

    def _get_redis_key(self, type_prefix: str, code: str, model_id: Optional[str] = None) -> str:
        """
        获取 Redis key，优先使用 model_id+code 联合查询
        新格式：semantic_model:{modelId}:[metric|dimension|entity]:{code}
        老格式：semantic_model:[metric|dimension|entity]:{code}
        """
        if model_id:
            return f'semantic_model:{model_id}:{type_prefix}:{code}'
        return f'semantic_model:{type_prefix}:{code}'

    @staticmethod
    def _payload_matches_model(data, model_id):
        # A model-qualified Redis key proves the namespace. An explicit model
        # inside that payload must agree; an unqualified legacy key cannot
        # supply missing data for a request that already named a model.
        return isinstance(data, dict) and (model_id is None or all(
            data.get(name) is None or str(data[name]) == str(model_id)
            for name in ('semantic_model_id', 'model_id')
        ))

    def _build_table_index(self, model_id: Optional[str] = None):
        """
        扫描 Redis 中所有实体，构建两个索引：
        - 表名 -> [entity_code, ...]（同表多实体时保留全部候选，调用方逐个尝试 JOIN）
        - 实体UUID(id) -> entity_code（通过 relation_config 的 target/source_entity_type_id 反查实体编码）
        使用 scan_iter 避免 keys 命令阻塞 Redis
        """
        # 如果已为当前 model_id 构建过索引，则跳过
        if self._index_built_model_id == model_id:
            return
        # 如果没有 model_id 且已构建过全局索引，则跳过
        if not model_id and self._index_built_global:
            return
            
        # 清空旧索引
        self._table_to_entity = {}
        self._entity_id_to_code = {}
        indexed_entities = []
        
        try:
            # 根据是否有 model_id 选择匹配模式
            if model_id:
                match_pattern = f'semantic_model:{model_id}:entity:*'
            else:
                match_pattern = f'{ENTITY_KEY_PREFIX}*'
                
            for key in self.redis.scan_iter(match=match_pattern, count=1000):
                raw = self.redis.get(key)
                if not raw:
                    continue
                try:
                    entity_data = json.loads(raw)
                    if not self._payload_matches_model(entity_data, model_id):
                        continue
                    code = entity_data.get('code')
                    table = entity_data.get('main_table_name') or entity_data.get('mapping_table')
                    entity_id = entity_data.get('id')
                    if code and table:
                        self._table_to_entity.setdefault(table, []).append(code)
                    if code and entity_id:
                        self._entity_id_to_code[str(entity_id)] = code
                    if code:
                        indexed_entities.append((str(code), str(table or ''), entity_data))
                except (json.JSONDecodeError, TypeError):
                    continue

            # Some platform Redis payload versions omit the entity's own
            # ``id`` while relation_config still stores UUID endpoints. Rebuild
            # those UUID mappings from the live relationship graph instead of
            # relying on a stale deployment-time copy. Direct physical-table
            # matches establish anchors first; incident relations then infer
            # the opposite endpoint for the entity record that contains them.
            for code, base_table, entity_data in indexed_entities:
                for relation in entity_data.get('semantic_model_relation_config', []) or []:
                    source_id = relation.get('source_entity_type_id')
                    target_id = relation.get('target_entity_type_id')
                    source_column = str(relation.get('source_table_column_name') or '')
                    target_column = str(relation.get('target_table_column_name') or '')
                    source_table = source_column.replace('-', '.').split('.', 1)[0]
                    target_table = target_column.replace('-', '.').split('.', 1)[0]
                    if source_id and base_table and source_table == base_table:
                        self._entity_id_to_code.setdefault(str(source_id), code)
                    if target_id and base_table and target_table == base_table:
                        self._entity_id_to_code.setdefault(str(target_id), code)

            for _ in range(2):
                changed = False
                for code, _, entity_data in indexed_entities:
                    for relation in entity_data.get('semantic_model_relation_config', []) or []:
                        source_id = str(relation.get('source_entity_type_id') or '')
                        target_id = str(relation.get('target_entity_type_id') or '')
                        source_code = self._entity_id_to_code.get(source_id)
                        target_code = self._entity_id_to_code.get(target_id)
                        if source_code and source_code != code and target_id and not target_code:
                            self._entity_id_to_code[target_id] = code
                            changed = True
                        elif target_code and target_code != code and source_id and not source_code:
                            self._entity_id_to_code[source_id] = code
                            changed = True
                if not changed:
                    break
        except redis.RedisError as e:
            print(f"[REDIS-WARN] 构建 table 索引失败: {e}")
            
        # 标记已构建索引
        if model_id:
            self._index_built_model_id = model_id
        else:
            self._index_built_global = True

    def _find_entity_code_by_table(self, table_name: str, model_id: Optional[str] = None) -> Optional[str]:
        """通过物理表名查找实体编码（返回第一个候选；同表多实体场景请用 find_all_entity_codes_by_table）"""
        self._build_table_index(model_id)
        codes = self._table_to_entity.get(table_name)
        return codes[0] if codes else None

    def find_all_entity_codes_by_table(self, table_name: str, model_id: Optional[str] = None) -> list:
        """通过物理表名查找所有候选实体编码（同表多实体时返回全部，供调用方逐个尝试 JOIN）"""
        self._build_table_index(model_id)
        return list(self._table_to_entity.get(table_name, []))

    def _find_entity_code_by_id(self, entity_id: str, model_id: Optional[str] = None) -> Optional[str]:
        """通过实体UUID(id)查找实体编码（用于 relation_config 的 target/source_entity_type_id）"""
        self._build_table_index(model_id)
        return self._entity_id_to_code.get(str(entity_id)) if entity_id else None

    def get_entity(self, entity_code: str, model_id: Optional[str] = None) -> Optional[Dict]:
        """获取实体定义（已适配为翻译器内部格式）"""
        cache_key = (model_id, entity_code)
        cached = self._cached('entity', self._entity_cache, cache_key)
        if cached is not None:
            return cached
        
        # 优先使用新格式查询（带 model_id）
        raw = None
        if model_id:
            new_key = self._get_redis_key('entity', entity_code, model_id)
            raw = self.redis.get(new_key)
        
        # 如果新格式没找到，尝试老格式
        if not raw and not model_id:
            old_key = self._get_redis_key('entity', entity_code)
            raw = self.redis.get(old_key)
            
        if not raw:
            return None
        try:
            data = json.loads(raw)
        except (json.JSONDecodeError, TypeError):
            return None
        if not self._payload_matches_model(data, model_id):
            return None
        adapted = self._adapt_entity(data, model_id)
        return self._store_cached('entity', self._entity_cache, cache_key, adapted)

