    def translate_only(self, asl_str: str, model_id: Optional[str] = None) -> Dict:
        """
        独立翻译方法：仅将ASL翻译为SQL，不执行查询

        Args:
            asl_str: ASL JSON字符串
            model_id: 语义模型ID（可选，用于Redis联合查询）

        Returns:
            dict: {
                "success": True/False,
                "sql": "生成的SQL语句",
                "error": "错误信息（失败时）",
                "model_id": "使用的model_id"
            }
        """
        try:
            ast_data = json.loads(asl_str)
        except json.JSONDecodeError as e:
            return {'success': False, 'sql': None, 'error': f"JSON解析错误: {str(e)}"}

        # 检查歧义
        ambiguity = ast_data.get('ambiguity', [])
        if ambiguity:
            questions = [{'type': a.get('type', ''), 'question': a.get('question', ''),
                          'candidates': a.get('candidates', [])} for a in ambiguity]
            return {
                'success': False,
                'sql': None,
                'error': 'DSL存在未解决的歧义，请先确认后再查询',
                'ambiguity': questions,
            }

        # 解析model_id
        resolved_model_id = model_id or ast_data.get('model_id') or ast_data.get('semantic_model_id')

        # 如果未提供model_id，尝试从指标反查
        if not resolved_model_id:
            metrics_in_ast = ast_data.get('metrics', []) or []
            resolved = self._resolve_model_id_from_metrics(metrics_in_ast, resolved_model_id)
            if resolved is not None:
                resolved_model_id = resolved

        # Resolve the physical source together with the semantic plan.  A model
        # can legally contain multiple data sources, therefore the execution
        # service must never rediscover one later by Redis scan order.
        explicit_data_source_id = ast_data.get('data_source_id')
        metric_data_source_id = self._resolve_data_source_id_from_metrics(
            ast_data.get('metrics', []) or [], resolved_model_id
        )
        subject_data_source_id = self._resolve_data_source_id_from_subject(
            ast_data.get('subject', {}) or {}, resolved_model_id
        )
        source_candidates = {
            str(item) for item in (
                explicit_data_source_id,
                metric_data_source_id,
                subject_data_source_id,
            ) if item not in (None, '')
        }
        if len(source_candidates) > 1:
            return {
                'success': False,
                'sql': None,
                'error': '语义查询引用了多个不一致的数据源，已阻止生成SQL',
                'error_code': 'DATA_SOURCE_SCOPE_MISMATCH',
                'retryable': False,
                'model_id': resolved_model_id,
            }
        resolved_data_source_id = next(iter(source_candidates), None)

        # 生成SQL
        try:
            sql = self.translate(asl_str, resolved_model_id)
            validation_report = self._semantic_sql_validation_report(
                ast_data, sql, resolved_model_id
            )
            return {
                'success': True,
                'sql': sql,
                'error': None,
                'model_id': resolved_model_id,
                'data_source_id': resolved_data_source_id,
                'semantic_validation_report': validation_report,
            }
        except Exception as e:
            return {
                'success': False, 'sql': None,
                'error': f"SQL生成失败: {str(e)}",
                'error_code': self._semantic_validation_error_code(str(e)),
                'retryable': False,
                'model_id': resolved_model_id,
                'semantic_validation_report': self._failed_semantic_validation_report(str(e)),
            }

    @staticmethod
    def _validation_check(code: str, status: str, message: str,
                          details: Optional[Dict] = None) -> Dict:
        return {
            'code': code, 'status': status, 'message': message,
            'details': details or {},
        }

    @classmethod
    def _semantic_validation_error_code(cls, message: str) -> str:
        mappings = (
            (r'不存在(实体|指标|维度|维度字段|过滤字段)', 'SEMANTIC_ASSET_NOT_FOUND'),
            (r'Join基数未配置', 'JOIN_CARDINALITY_MISSING'),
            (r'一对多Join会导致指标重复累计', 'AGGREGATION_FANOUT_RISK'),
            (r'无法确定主实体|无法找到从.*到.*的关联路径', 'RELATIONSHIP_PATH_NOT_FOUND'),
            (r'歧义', 'SEMANTIC_AMBIGUITY'),
            (r'LIMIT|HAVING|DISTINCT投影|未包含指标或明细字段', 'QUERY_SHAPE_INVALID'),
            (r'JSON|AST必须|必须是', 'ASL_SYNTAX_INVALID'),
        )
        for pattern, code in mappings:
            if re.search(pattern, message, re.I):
                return code
        return 'SEMANTIC_VALIDATION_FAILED'

    @classmethod
    def _failed_semantic_validation_report(cls, message: str) -> Dict:
        code = cls._semantic_validation_error_code(message)
        layer = (
            'SYNTAX' if code == 'ASL_SYNTAX_INVALID'
            else 'BUSINESS' if code == 'QUERY_SHAPE_INVALID'
            else 'SEMANTIC'
        )
        return {
            'schema_version': '1.0', 'status': 'FAIL',
            'layers': {
                'syntax': {'status': 'FAIL' if layer == 'SYNTAX' else 'NOT_RUN', 'checks': []},
                'semantic': {'status': 'FAIL' if layer == 'SEMANTIC' else 'NOT_RUN', 'checks': []},
                'business': {'status': 'FAIL' if layer == 'BUSINESS' else 'NOT_RUN', 'checks': []},
            },
            'errors': [{'code': code, 'layer': layer, 'message': message}],
            'warnings': [],
        }

    def _semantic_sql_validation_report(
        self, ast: Dict, sql: str, model_id: Optional[str]
    ) -> Dict:
        self.validate_read_only_sql(sql)
        metrics = ast.get('metrics') or []
        dimensions = ast.get('dimensions') or []
        syntax_checks = [
            self._validation_check(
                'READ_ONLY_SINGLE_STATEMENT', 'PASS',
                'SQL为单条只读SELECT/WITH语句且不包含危险操作',
            ),
            self._validation_check(
                'ASL_SCHEMA_VALID', 'PASS', 'ASL结构与字段类型已通过校验',
            ),
        ]
        semantic_checks = [
            self._validation_check(
                'SEMANTIC_ASSETS_REGISTERED', 'PASS',
                '查询实体、指标、维度和过滤字段均来自当前语义模型',
                {'semantic_model_id': str(model_id)},
            ),
            self._validation_check(
                'DECLARED_RELATIONSHIPS_ONLY', 'PASS',
                'SQL Join仅由已发布语义关系和子表映射生成',
            ),
            self._validation_check(
                'AGGREGATE_CARDINALITY_SAFE', 'PASS',
                '指标聚合已通过关系基数与一对多膨胀检查',
                {'metric_count': len(metrics), 'dimension_count': len(dimensions)},
            ),
            self._validation_check(
                'METRIC_FORMULA_BOUND', 'PASS' if metrics else 'NOT_APPLICABLE',
                '指标表达式来自已发布指标公式' if metrics else '本次为无指标明细投影',
            ),
        ]
        business_checks = [
            self._validation_check(
                'GLOBAL_FILTER_RULES_APPLIED', 'PASS' if metrics else 'NOT_APPLICABLE',
                '所选指标的全局业务过滤规则已合并到查询' if metrics else '明细投影无指标全局规则',
            ),
            self._validation_check(
                'TIME_CONTEXT_APPLIED', 'PASS' if ast.get('time_context') else 'NOT_APPLICABLE',
                '时间范围使用声明的时间锚点' if ast.get('time_context') else '本次查询未声明时间范围',
            ),
            self._validation_check(
                'QUERY_SHAPE_VALID', 'PASS',
                '明细/聚合、DISTINCT、HAVING、排序和LIMIT组合合法',
            ),
        ]
        return {
            'schema_version': '1.0', 'status': 'PASS',
            'layers': {
                'syntax': {'status': 'PASS', 'checks': syntax_checks},
                'semantic': {'status': 'PASS', 'checks': semantic_checks},
                'business': {'status': 'PASS', 'checks': business_checks},
            },
            'errors': [], 'warnings': [],
        }

    def execute_sql_only(self, sql: str, model_id: Optional[str] = None, 
                         data_source_id: Optional[str] = None) -> Dict:
        """
        独立执行方法：执行SQL并返回结果，支持大数据量自动导出Excel到MinIO

        Args:
            sql: 要执行的SQL语句
            model_id: 语义模型ID（用于查找数据源）
            data_source_id: 数据源ID（可选，优先级高于model_id）

        Returns:
            dict: {
                "success": True/False,
                "sql": "执行的SQL",
                "row_count": 行数,
                "columns": 列名列表,
                "data": 数据列表（>200条时为前20条预览）,
                "download_url": Excel下载URL（>200条时）,
                "error": "错误信息（失败时）"
            }
        """
        from data_exporter import format_query_result

        try:
            sql = self.validate_read_only_sql(sql)
        except ValueError:
            return {
                'success': False,
                'sql': sql if isinstance(sql, str) else None,
                'error': 'SQL was rejected by the read-only safety policy',
                'error_code': 'SQL_SAFETY_REJECTED',
                'retryable': False,
            }

        # 查找数据源
        try:
            ds_config = self.fetch_data_source(model_id, data_source_id)
        except Exception as e:
            return {'success': False, 'sql': sql, 'error': f"数据源查询失败: {str(e)}"}

        if not ds_config:
            return {'success': False, 'sql': sql, 
                    'error': f"Redis中未找到对应的数据源配置(model_id={model_id}, data_source_id={data_source_id})"}

        # 执行SQL
        watermark_model_id = model_id or ds_config.get('semantic_model_id')
        source_watermark_field = self._resolve_source_watermark_field(
            sql, watermark_model_id
        )
        exec_result = self.execute_sql_on_data_source(
            sql, ds_config, source_watermark_field
        )
        if not exec_result['success']:
            return {
                'success': False,
                'sql': sql,
                'error': exec_result.get('error'),
                'error_code': exec_result.get('error_code'),
                'retryable': bool(exec_result.get('retryable')),
            }

        # 格式化结果（自动判断是否需要导出Excel）
        result = format_query_result(
            columns=exec_result.get('columns', []),
            data=exec_result.get('data', []),
            row_count=exec_result.get('row_count', 0),
            sql=sql,
        )
        for evidence_field in (
            'snapshot_id', 'data_as_of', 'quality_status', 'quality_checks',
            'source_data_as_of', 'source_watermark_field',
        ):
            if evidence_field in exec_result:
                result[evidence_field] = exec_result[evidence_field]
        result['data_source'] = {
            'id': ds_config.get('id'),
            'name': ds_config.get('name'),
            'host': ds_config.get('host'),
            'db_name': ds_config.get('db_name'),
        }
        return result

    def execute_query(self, ast_json: str, model_id: Optional[str] = None) -> Dict:
        """
        执行 AST 查询：生成 SQL -> 查询数据源 -> 执行 SQL -> 返回结果

        AST 中应包含 model_id 字段（语义模型 id），用于关联数据源。
        也支持直接传入 data_source_id 字段。

        :param ast_json: AST 结构化数据的 JSON 字符串
        :param model_id: 可选的模型 id，用于 DSL 数据的联合查询
        :return: 查询结果字典
        """
        try:
            ast_data = json.loads(ast_json)
        except json.JSONDecodeError as e:
            return {'sql': None, 'success': False, 'error': '请求中的ASL不是合法JSON',
                    'error_code': 'INVALID_ASL', 'retryable': False}

        # 检查歧义
        ambiguity = ast_data.get('ambiguity', [])
        if ambiguity:
            questions = [{'type': a.get('type', ''), 'question': a.get('question', ''),
                          'candidates': a.get('candidates', [])} for a in ambiguity]
            return {
                'success': False,
                'error': 'DSL存在未解决的歧义，请先确认后再查询',
                'ambiguity': questions,
            }

        # 获取 model_id / data_source_id
        # 优先级：传入的 model_id > AST 显式传入 > 从指标关联实体反查 data_source_id > 从 subject.entity 反查 data_source_id > 从指标反查 semantic_model_id
        model_id = model_id or ast_data.get('model_id') or ast_data.get('semantic_model_id')
        if model_id is None:
            return {
                'sql': None, 'success': False,
                'error': '必须提供semantic_model_id',
                'error_code': 'SEMANTIC_MODEL_REQUIRED', 'retryable': False,
            }
        try:
            model_id = str(_positive_int(model_id))
        except ValueError:
            return {
                'sql': None, 'success': False,
                'error': 'semantic_model_id必须是正整数',
                'error_code': 'INVALID_SEMANTIC_MODEL_ID', 'retryable': False,
            }
        data_source_id = ast_data.get('data_source_id')

        # AST 未提供 model_id/data_source_id 时，优先从指标关联实体反查 data_source_id
        # （实体在 Redis 中存储了 data_source_id 字段，O(1) 精确查找）
        if not model_id and not data_source_id:
            data_source_id = self._resolve_data_source_id_from_metrics(ast_data.get('metrics', []) or [], model_id)

        # 仍未找到时，尝试从 subject.entity 反查 data_source_id
        if not model_id and not data_source_id:
            data_source_id = self._resolve_data_source_id_from_subject(ast_data.get('subject', {}), model_id)

        # 仍未找到时，从指标反查 semantic_model_id（按模型 id 扫描数据源）
        if not model_id and not data_source_id:
            metrics_in_ast = ast_data.get('metrics', []) or []
            resolved = self._resolve_model_id_from_metrics(metrics_in_ast, model_id)
            if resolved is not None:
                model_id = resolved

        # 生成 SQL
        try:
            sql = self.translate(ast_json, model_id)
        except (redis.ConnectionError, redis.TimeoutError):
            return {
                'sql': None, 'success': False,
                'error': '语义DSL服务暂时不可用',
                'error_code': 'SEMANTIC_DSL_UNAVAILABLE', 'retryable': True,
            }
        except Exception as e:
            return {'sql': None, 'success': False, 'error': f"SQL生成失败: {str(e)}",
                    'error_code': 'SQL_TRANSLATION_FAILED', 'retryable': False}

        if not model_id and not data_source_id:
            return {
                'sql': sql,
                'success': False,
                'error': 'AST中未提供 model_id 或 data_source_id，且无法从指标反查 semantic_model_id 或从关联实体反查 data_source_id，无法关联数据源',
            }

        # 查询数据源配置
        try:
            ds_config = self.fetch_data_source(model_id, data_source_id)
        except Exception as e:
            return {'sql': sql, 'success': False, 'error': f"数据源查询失败: {str(e)}"}

        if not ds_config:
            return {'sql': sql, 'success': False, 'error': f"Redis中未找到对应的数据源配置(model_id={model_id}, data_source_id={data_source_id})"}

        # 执行 SQL
        watermark_model_id = model_id or ds_config.get('semantic_model_id')
        source_watermark_field = self._resolve_source_watermark_field(
            sql, watermark_model_id
        )
        exec_result = self.execute_sql_on_data_source(
            sql, ds_config, source_watermark_field
        )
        if not exec_result['success']:
            return {
                'sql': sql,
                'success': False,
                'error': exec_result.get('error'),
                'data_source': {
                    'id': ds_config.get('id'),
                    'name': ds_config.get('name'),
                    'host': ds_config.get('host'),
                    'db_name': ds_config.get('db_name'),
                },
            }

        # 使用统一的结果格式化（支持大数据量导出Excel）
        from data_exporter import format_query_result
        result = format_query_result(
            columns=exec_result.get('columns', []),
            data=exec_result.get('data', []),
            row_count=exec_result.get('row_count', 0),
            sql=sql,
        )
        for evidence_field in (
            'snapshot_id', 'data_as_of', 'quality_status', 'quality_checks',
            'source_data_as_of', 'source_watermark_field',
        ):
            if evidence_field in exec_result:
                result[evidence_field] = exec_result[evidence_field]
        result['data_source'] = {
            'id': ds_config.get('id'),
            'name': ds_config.get('name'),
            'host': ds_config.get('host'),
            'db_name': ds_config.get('db_name'),
        }
        return result


